  isExpanded?: boolean;
  category?: "Common" | "Exotic" | "Monstrous" | "Setting";
  abilityBonuses: Partial<Record<StatKey, number>>;
  hasFlexibleBonuses?: boolean;
  flexibleBonusCount?: number;
  flexibleBonusValue?: number;
  flexibleBonusDisallowed?: StatKey[]; // stats that already have a fixed bonus
